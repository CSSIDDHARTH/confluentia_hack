def test_score_equals_100_minus_sum_of_weights():
    det, planogram, catalogue = _load()
    report = compute_report(det, planogram, catalogue)

    expected_penalty = sum(WEIGHTS[v.kind] for v in report.violations)
    assert report.score == round(max(0.0, 100.0 - expected_penalty), 1)
    assert 0 <= report.score <= 100


def test_fully_compliant_image_scores_100():
    # Build a synthetic detection with exactly min_facings matching items
    # per slot, no gaps and no labels -- nothing here should ever violate.
    _, planogram, catalogue = _load()

    items = []
    x = 0
    for shelf in planogram.shelves:
        for slot in shelf.slots:
            for n in range(slot.min_facings):
                items.append(
                    Item(
                        item_id=f"synth-{slot.slot_id}-{n}",
                        bbox=[x, 0, x + 50, 50],
                        det_confidence=0.99,
                        sku=slot.sku,
                        sku_confidence=0.99,
                        shelf_id=shelf.shelf_id,
                        slot_id=slot.slot_id,
                    )
                )
                x += 60

    clean = DetectionOutput(
        image_id="synthetic-clean",
        image_path="data/mock/mock_shelf_001.png",
        image_width=10_000,
        image_height=900,
        planogram_id=planogram.planogram_id,
        captured_at="2026-10-20T09:30:00Z",
        items=items,
    )

    report = compute_report(clean, planogram, catalogue)

    assert report.violations == []
    assert report.score == 100.0


def test_counts_sum_to_number_of_violations():
    det, planogram, catalogue = _load()
    report = compute_report(det, planogram, catalogue)

    assert sum(report.counts.values()) == len(report.violations)


def test_lowstock_fixture_exercises_low_stock_alongside_the_other_categories():
    # The canonical example never trips LOW_STOCK (its partial slot sits
    # exactly at min_facings). This scenario, generated by
    # scripts/gen_scenario.py, does, alongside the other four categories.
    det = load_detection_output(MOCK / "mock_shelf_002_lowstock.json")
    planogram = load_planogram(CONTRACTS / "planogram.example.json")
    catalogue = load_catalogue(CONTRACTS / "catalogue.example.csv")

    report = compute_report(det, planogram, catalogue)
    kinds = {v.kind for v in report.violations}

    assert kinds == {
        ViolationKind.STOCK_OUT,
        ViolationKind.LOW_STOCK,
        ViolationKind.MISPLACED,
        ViolationKind.UNRECOGNISED_ITEM,
        ViolationKind.PRICE_MISMATCH,
    }

    low_stock = [v for v in report.violations if v.kind == ViolationKind.LOW_STOCK]
    assert len(low_stock) == 1
    assert low_stock[0].slot_id == "S1-01"


def test_near_clean_scenario_only_has_the_unreadable_price():
    det = load_detection_output(MOCK / "mock_shelf_003_clean.json")
    planogram = load_planogram(CONTRACTS / "planogram.example.json")
    catalogue = load_catalogue(CONTRACTS / "catalogue.example.csv")

    report = compute_report(det, planogram, catalogue)

    assert [(v.kind, v.slot_id) for v in report.violations] == [
        (ViolationKind.UNREADABLE_PRICE, "S1-03")
    ]
    assert report.score == 100 - WEIGHTS[ViolationKind.UNREADABLE_PRICE]


def test_generated_scenarios_stay_inside_the_image():
    for name in ("mock_shelf_002_lowstock.json", "mock_shelf_003_clean.json"):
        det = load_detection_output(MOCK / name)
        for obj in [*det.shelves, *det.items, *det.gaps, *det.labels]:
            x1, y1, x2, y2 = obj.bbox
            assert 0 <= x1 < x2 <= det.image_width
            assert 0 <= y1 < y2 <= det.image_height
