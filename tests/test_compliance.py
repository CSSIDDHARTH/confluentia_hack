from pathlib import Path

from shelfsense.contracts import DetectionOutput, Item, load_catalogue, load_detection_output, load_planogram
from shelfsense.report.compliance import ViolationKind, WEIGHTS, compute_report

CONTRACTS = Path(__file__).resolve().parents[1] / "contracts"
MOCK = Path(__file__).resolve().parents[1] / "data" / "mock"


def _load():
    det = load_detection_output(CONTRACTS / "detection_output.example.json")
    planogram = load_planogram(CONTRACTS / "planogram.example.json")
    catalogue = load_catalogue(CONTRACTS / "catalogue.example.csv")
    return det, planogram, catalogue


def test_example_detection_finds_the_planted_violations():
    # The example detection output is designed (per CLAUDE.md) to contain a
    # misplaced product, a stock-out, a price mismatch and an unrecognised
    # item. (Its one partially-filled slot, S1-03, has matching facings
    # equal to -- not below -- min_facings, so it is not a low-stock
    # violation under assumption 5; see compliance.py's module docstring.)
    det, planogram, catalogue = _load()

    report = compute_report(det, planogram, catalogue)
    kinds = {v.kind for v in report.violations}

    assert kinds == {
        ViolationKind.STOCK_OUT,
        ViolationKind.MISPLACED,
        ViolationKind.UNRECOGNISED_ITEM,
        ViolationKind.PRICE_MISMATCH,
    }


def test_stock_out_is_slot_s2_02():
    det, planogram, catalogue = _load()
    report = compute_report(det, planogram, catalogue)

    stock_outs = [v for v in report.violations if v.kind == ViolationKind.STOCK_OUT]
    assert [v.slot_id for v in stock_outs] == ["S2-02"]
    assert stock_outs[0].sku == "SKU-2002"


def test_misplaced_item_is_sku_2002_in_slot_s1_02():
    det, planogram, catalogue = _load()
